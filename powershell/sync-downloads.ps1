<#
.SYNOPSIS
Install a prepared artifact set and derive the site's checksums from its bytes.
#>

param(
    [Parameter(Mandatory=$true)]
    [string]$FromDir
)

$ErrorActionPreference = "Stop"

# Resolve paths
$scriptPath = Resolve-Path $MyInvocation.MyCommand.Path
$site = Split-Path (Split-Path $scriptPath -Parent) -Parent

# Read manifest version
$manifestPath = Join-Path (Split-Path $site -Parent) "plugin-source/browser-extension/manifest.json"
$version = (Get-Content $manifestPath | ConvertFrom-Json).version

# Define artifact names
$names = @(
    "tiktok-live-companion-extension-$version.zip",
    "tiktok-live-companion-plugin-$version.zip",
    "tiktok-live-companion-service-$version.zip",
    "tiktok-live-companion-android-$version-source.zip",
    "tiktok-live-companion-ios-$version-source.zip"
)

$apkName = "tiktok-live-companion-android-$version.apk"
if (Test-Path (Join-Path $FromDir $apkName)) {
    $names += $apkName
}

# Validate ZIP files
foreach ($name in $names) {
    $src = Join-Path $FromDir $name
    if (-not (Test-Path $src)) {
        throw "Missing file: $src"
    }
    
    try {
        $zip = [System.IO.Compression.ZipFile]::OpenRead($src)
        foreach ($entry in $zip.Entries) {
            # Just accessing entries to validate
        }
        $zip.Dispose()
    } catch {
        throw "Corrupt ZIP: $name"
    }
    
    # Check manifest version for extension
    if ($name -like "*extension*" -and (Test-Path $src)) {
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $zip = [System.IO.Compression.ZipFile]::OpenRead($src)
        $manifestEntry = $zip.GetEntry("manifest.json")
        if ($manifestEntry) {
            $stream = $manifestEntry.Open()
            $reader = New-Object System.IO.StreamReader($stream)
            $manifestContent = $reader.ReadToEnd()
            $reader.Close()
            $stream.Close()
            $zip.Dispose()
            
            $manifestVersion = (ConvertFrom-Json $manifestContent).version
            if ($manifestVersion -ne $version) {
                throw "Manifest version mismatch"
            }
        } else {
            $zip.Dispose()
            throw "manifest.json not found in ZIP: $name"
        }
    }
}

# Copy files
$downloadsDir = Join-Path $site "public/downloads"
if (-not (Test-Path $downloadsDir)) {
    New-Item -ItemType Directory -Path $downloadsDir | Out-Null
}

foreach ($name in $names) {
    $src = Join-Path $FromDir $name
    $dest = Join-Path $downloadsDir $name
    Copy-Item $src $dest -Force
}

# Generate hashes
$hashes = ""
foreach ($name in $names) {
    $filePath = Join-Path $downloadsDir $name
    $bytes = [System.IO.File]::ReadAllBytes($filePath)
    $hash = [System.Security.Cryptography.SHA256]::Create().ComputeHash($bytes)
    $hashString = [BitConverter]::ToString($hash).Replace("-", "").ToLower()
    $hashes += "$hashString  $name`n"
}

# Write SHA256 checksum file
$checksumFile = Join-Path $downloadsDir "tiktok-live-companion-$version-SHA256.txt"
Set-Content $checksumFile $hashes -Encoding UTF8

# Write TypeScript file
$tsContent = "// Generated by site/scripts/sync-downloads.py; do not edit by hand.`nexport const downloadChecksums = " + 
             (ConvertTo-Json $hashes -Compress) + ";`n"
$tsFile = Join-Path $site "src/download-checksums.ts"
Set-Content $tsFile $tsContent -Encoding UTF8

Write-Output $hashes
