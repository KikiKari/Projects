    file << "    iso = !iso; kamera = iso ? kameraIso : kameraPersp;\n";
    file << "    this.setAttribute(\"aria-pressed\", String(iso));\n";
    file << "    this.textContent = iso ? \"Iso\" : \"Persp\";\n";
    file << "    groesse();\n";
    file << "  });\n";
    file << "\n";
    file << "  function groesse(){\n";
    file << "    var w = buehne.clientWidth, h = buehne.clientHeight;\n";
    file << "    aspekt = w / h;\n";
    file << "    kameraIso.left = -D*aspekt; kameraIso.right = D*aspekt;\n";
    file << "    kameraIso.top = D; kameraIso.bottom = -D; kameraIso.updateProjectionMatrix();\n";
    file << "    kameraPersp.aspect = aspekt; kameraPersp.updateProjectionMatrix();\n";
    file << "    renderer.setSize(w, h, false);\n";
    file << "  }\n";
    file << "  window.addEventListener(\"resize\", groesse);\n";
    file << "\n";
    file << "  groesse();\n";
    file << "  waehle(0);\n";
