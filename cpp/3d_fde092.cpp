    file << "    document.getElementById(\"btn-iso\").setAttribute(\"aria-pressed\", \"true\");\n";
    file << "    document.getElementById(\"btn-iso\").textContent = \"Iso\";\n";
    file << "    waehle(0); groesse();\n";
    file << "  });\n";
