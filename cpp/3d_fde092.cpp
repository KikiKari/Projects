    file << "  window.addEventListener(\"pointerup\", function(){ zieht = false; setTimeout(function(){ gezogen = false; }, 0); });\n";
    file << "\n";
    file << "  function zoom(f){\n";
    file << "    if (iso){ D = Math.max(11, Math.min(54, D * f)); groesse(); }\n";
    file << "    else { radius = Math.max(32, Math.min(160, radius * f)); }\n";
    file << "  }\n";
    file << "  document.getElementById(\"btn-plus\").addEventListener(\"click\", function(){ zoom(0.85); });\n";
    file << "  document.getElementById(\"btn-minus\").addEventListener(\"click\", function(){ zoom(1.18); });\n";
    file << "  renderer.domElement.addEventListener(\"wheel\", function(e){\n";
    file << "    e.preventDefault(); zoom(e.deltaY > 0 ? 1.08 : 0.93);\n";
    file << "  }, {passive:false});\n";
    file << "  document.getElementById(\"btn-reset\").addEventListener(\"click\", function(){\n";
    file << "    azimut = Math.PI/4; elevation = 0.62; D = 26; radius = 82; rotiert = true;\n";
