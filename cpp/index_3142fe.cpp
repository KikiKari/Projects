void writeHtmlDocument(const std::string& filename) {
    std::ofstream file(filename);
    if (!file.is_open()) {
        std::cerr << "Error: Could not open file " << filename << " for writing." << std::endl;
        return;
    }

    // Write DOCTYPE
    file << "<!DOCTYPE html>\n";
    
    // Write html tag with language attribute
    file << "<html lang=\"de\">\n";
    
    // Write head section
    file << "  <head>\n";
    file << "    <meta charset=\"UTF-8\" />\n";
    file << "    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no\" />\n";
    file << "    <meta name=\"theme-color\" content=\"#0d1b2a\" />\n";
    file << "    <meta name=\"description\" content=\"Lokaler Regen-Check für die nächsten 30, 60 und 120 Minuten\" />\n";
    file << "    <meta name=\"apple-mobile-web-app-capable\" content=\"yes\" />\n";
    file << "    <meta name=\"apple-mobile-web-app-status-bar-style\" content=\"black-translucent\" />\n";
    file << "    <meta name=\"apple-mobile-web-app-title\" content=\"Weather\" />\n";
    file << "    <link rel=\"manifest\" href=\"./manifest.json\" />\n";
    file << "    <link rel=\"apple-touch-icon\" href=\"./icon-512.png\" />\n";
    file << "    <title>Weather – Regen-Check</title>\n";
    file << "    <script type=\"module\" crossorigin src=\"./assets/index-DGdzG44S.js\"></script>\n";
    file << "    <link rel=\"stylesheet\" crossorigin href=\"./assets/index-erFv57XC.css\">\n";
    file << "  </head>\n";
    
    // Write body section
    file << "  <body>\n";
    file << "    <div id=\"root\"></div>\n";
    
    // Write embedded script
    file << "  <script data-pplx-inline-edit>\n";
    file << "(function () {\n";
    file << "  if (window === window.top) return;\n";
    file << "\n";
    file << "  const allowedParentOrigins = [\"https://www.perplexity.ai\",\"https://perplexity.ai\",\"https://testing.perplexity.ai\",\"https://staging.perplexity.ai\",\"https://*.preview.i.perplexity.ai\",\"http://localhost:3000\",\"http://127.0.0.1:3000\",\"http://localhost:5173\",\"http://127.0.0.1:5173\"];\n";
    file << "  const MAX_FONT_BYTES = 500 * 1024;\n";
    file << "  const MAX_TOTAL_FONT_BYTES = 2 * 1024 * 1024;\n";
    file << "  let scrollForwarding = false;\n";
    file << "  let scrollRaf = 0;\n";
    file << "  let trustedTopOrigin = null;\n";
    file << "\n";
    file << "  // Allow entries like \"https://*.preview.i.perplexity.ai\" — the wildcard\n";
    file << "  // matches a single DNS label (no dots), so \"https://*.foo\" cannot stretch\n";
    file << "  // across multiple labels.\n";
    file << "  function matchesAllowedOrigin(origin) {\n";
    file << "    if (!origin) return false;\n";
    file << "    for (const entry of allowedParentOrigins) {\n";
    file << "      if (!entry.includes(\"*\")) {\n";
    file << "        if (entry === origin) return true;\n";
    file << "        continue;\n";
    file << "      }\n";
    file << "      const pattern = new RegExp(\n";
    file << "        \"^\" +\n";
    file << "          entry.replace(/[.+?^${}()|[\\]\\\\]/g, \"\\\\$&\").replace(/\\*/g, \"[^.]+\") +\n";
    file << "          \"$\",\n";
    file << "      );\n";
    file << "      if (pattern.test(origin)) return true;\n";
    file << "    }\n";
    file << "    return false;\n";
    file << "  }\n";
    file << "\n";
    file << "  // Trust decision: when the sender is same-origin-visible (event.origin is a\n";
    file << "  // real origin like https://www.perplexity.ai) we trust event.origin directly.\n";
    file << "  // When event.origin is \"null\" (opaque broker srcdoc), we fall back to the\n";
    file << "  // broker's stamped `parentOrigin` to identify the top window. The fallback\n";
    file << "  // is claim-only — we rely on the browser's native `targetOrigin` enforcement\n";
    file << "  // on the response path (see postToTrustedTop) to ensure replies can't be\n";
    file << "  // delivered to anyone but the actual top window of that claimed origin.\n";
    file << "  function getTrustedParentOrigin(event) {\n";
    file << "    const forwardedParentOrigin =\n";
    file << "      typeof event.data.parentOrigin === \"string\" ? event.data.parentOrigin : null;\n";
    file << "    const parentOrigin = event.origin === \"null\" ? forwardedParentOrigin : event.origin;\n";
    file << "    return matchesAllowedOrigin(parentOrigin) ? parentOrigin : null;\n";
    file << "  }\n";
    file << "\n";
    file << "  // All responses go to window.top with targetOrigin = the allowlisted origin.\n";
    file << "  // An attacker that iframes us inside their own null-origin broker can claim\n";
    file << "  // any parentOrigin they like, but the browser will drop the reply whenever\n";
    file << "  // the real top's origin doesn't match — so the screenshot never leaves.\n";
    file << "  function postToTrustedTop(message) {\n";
    file << "    if (!trustedTopOrigin) return;\n";
    file << "    try {\n";
    file << "      window.top.postMessage(message, trustedTopOrigin);\n";
    file << "    } catch (_error) {}\n";
    file << "  }\n";
    file << "\n";
    file << "  function inlineAll(original, clone) {\n";
    file << "    if (original.nodeType !== 1 || clone.nodeType !== 1) return;\n";
    file << "\n";
    file << "    try {\n";
    file << "      const computedStyle = getComputedStyle(original);\n";
    file << "      // cssText on a computed style is the serialized declaration in modern\n";
    file << "      // Chromium/Safari — a single read beats enumerating ~400 longhand\n";
    file << "      // properties. Firefox returns \"\" here, so we fall back on empty.\n";
    file << "      const serialized = computedStyle.cssText;\n";
    file << "      if (serialized) {\n";
    file << "        clone.style.cssText = serialized;\n";
    file << "      } else {\n";
    file << "        const parts = new Array(computedStyle.length);\n";
    file << "        for (let index = 0; index < computedStyle.length; index += 1) {\n";
    file << "          const property = computedStyle[index];\n";
    file << "          parts[index] = `${property}:${computedStyle.getPropertyValue(property)};`;\n";
    file << "        }\n";
    file << "        clone.style.cssText = parts.join(\"\");\n";
    file << "      }\n";
    file << "    } catch (_error) {}\n";
    file << "\n";
    file << "    const originalChildren = original.children;\n";
    file << "    const clonedChildren = clone.children;\n";
    file << "    for (\n";
    file << "      let index = 0;\n";
    file << "      index < originalChildren.length && index < clonedChildren.length;\n";
    file << "      index += 1\n";
    file << "    ) {\n";
    file << "      inlineAll(originalChildren[index], clonedChildren[index]);\n";
    file << "    }\n";
    file << "  }\n";
    file << "\n";
    file << "  function extractFontUrl(srcValue) {\n";
    file << "    const matches = [\n";
    file << "      ...srcValue.matchAll(\n";
    file << "        /url\\([\"']?([^\"')]+)[\"']?\\)(?:\\s*format\\([\"']?([^\"')]+)[\"']?\\))?/gi,\n";
    file << "      ),\n";
    file << "    ];\n";
    file << "    if (matches.length === 0) return null;\n";
    file << "    const woff2 = matches.find((m) => m[2] && m[2].toLowerCase().includes(\"woff2\"));\n";
    file << "    if (woff2) return woff2[1];\n";
    file << "    const woff = matches.find((m) => m[2] && m[2].toLowerCase().includes(\"woff\"));\n";
    file << "    if (woff) return woff[1];\n";
    file << "    return matches[0][1];\n";
    file << "  }\n";
    file << "\n";
    file << "  // Cache resolved font URL -> data URI across captures. Fonts on a page\n";
    file << "  // essentially never change, and a batch run emits multiple captures back to\n";
    file << "  // back — without this we'd refetch + re-base64 every time.\n";
    file << "  const fontDataUriCache = new Map();\n";
    file << "  const SRC_DECLARATION_RE = /src\\s*:\\s*[^;}]+/i;\n";
    file << "\n";
    file << "  async function fetchAsDataUri(url) {\n";
    file << "    if (fontDataUriCache.has(url)) return fontDataUriCache.get(url);\n";
    file << "    let dataUri = null;\n";
    file << "    try {\n";
    file << "      const response = await fetch(url, { mode: \"cors\", credentials: \"omit\" });\n";
    file << "      if (response.ok) {\n";
    file << "        const blob = await response.blob();\n";
    file << "        if (blob.size <= MAX_FONT_BYTES) {\n";
    file << "          dataUri = await new Promise((resolve) => {\n";
    file << "            const reader = new FileReader();\n";
    file << "            reader.onloadend = () =>\n";
    file << "              resolve(typeof reader.result === \"string\" ? reader.result : null);\n";
    file << "            reader.onerror = () => resolve(null);\n";
    file << "            reader.readAsDataURL(blob);\n";
    file << "          });\n";
    file << "        }\n";
    file << "      }\n";
    file << "    } catch (_error) {\n";
    file << "      dataUri = null;\n";
    file << "    }\n";
    file << "    fontDataUriCache.set(url, dataUri);\n";
    file << "    return dataUri;\n";
    file << "  }\n";
    file << "\n";
    file << "  function collectFontFaceRuleTexts() {\n";
    file << "    const rules = [];\n";
    file << "    for (const sheet of document.styleSheets) {\n";
    file << "      let cssRules;\n";
    file << "      try {\n";
    file << "        cssRules = sheet.cssRules;\n";
    file << "      } catch (_error) {\n";
    file << "        continue;\n";
    file << "      }\n";
    file << "      if (!cssRules) continue;\n";
    file << "      for (const rule of cssRules) {\n";
    file << "        const cssText = rule.cssText || \"\";\n";
    file << "        if (cssText.startsWith(\"@font-face\")) rules.push(cssText);\n";
    file << "      }\n";
    file << "    }\n";
    file << "    return rules;\n";
    file << "  }\n";
    file << "\n";
    file << "  async function buildInlinedFontCss() {\n";
    file << "    const ruleTexts = collectFontFaceRuleTexts();\n";
    file << "    if (ruleTexts.length === 0) return null;\n";
    file << "\n";
    file << "    const resolved = ruleTexts.map((cssText) => {\n";
    file << "      if (!SRC_DECLARATION_RE.test(cssText)) return null;\n";
    file << "      const srcMatch = cssText.match(/src\\s*:\\s*([^;}]+)[;}]/i);\n";
    file << "      if (!srcMatch) return null;\n";
    file << "      const url = extractFontUrl(srcMatch[1]);\n";
    file << "      if (!url) return null;\n";
    file << "      try {\n";
    file << "        return { cssText, url: new URL(url, document.baseURI).href };\n";
    file << "      } catch (_error) {\n";
    file << "        return null;\n";
    file << "      }\n";
    file << "    });\n";
    file << "\n";
    file << "    const dataUris = await Promise.all(\n";
    file << "      resolved.map((entry) => (entry ? fetchAsDataUri(entry.url) : Promise.resolve(null))),\n";
    file << "    );\n";
    file << "\n";
    file << "    const inlined = [];\n";
    file << "    let totalBytes = 0;\n";
    file << "    for (let index = 0; index < resolved.length; index += 1) {\n";
    file << "      const entry = resolved[index];\n";
    file << "      const dataUri = dataUris[index];\n";
    file << "      if (!entry || !dataUri) continue;\n";
    file << "      const approxBytes = dataUri.length * 0.75;\n";
    file << "      if (totalBytes + approxBytes > MAX_TOTAL_FONT_BYTES) break;\n";
    file << "      totalBytes += approxBytes;\n";
    file << "      inlined.push(entry.cssText.replace(SRC_DECLARATION_RE, `src: url(\"${dataUri}\")`));\n";
    file << "    }\n";
    file << "    return inlined.length > 0 ? inlined.join(\"\\n\") : null;\n";
    file << "  }\n";
    file << "\n";
    file << "  function stripExternal(clone) {\n";
    file << "    const images = clone.querySelectorAll(\"img\");\n";
    file << "    for (let index = 0; index < images.length; index += 1) {\n";
    file << "      const src = images[index].getAttribute(\"src\");\n";
    file << "      if (src && !src.startsWith(\"data:\")) images[index].removeAttribute(\"src\");\n";
    file << "    }\n";
    file << "\n";
    file << "    const elements = clone.querySelectorAll(\"*\");\n";
    file << "    for (let index = 0; index < elements.length; index += 1) {\n";
    file << "      const style = elements[index].style.cssText;\n";
    file << "      if (style && style.includes(\"url(\")) {\n";
    file << "        elements[index].style.cssText = style.replace(\n";
    file << "          /url\\([\"']?(?!data:)[^)\"']*[\"']?\\)/gi,\n";
    file << "          \"none\",\n";
    file << "        );\n";
    file << "      }\n";
    file << "    }\n";
    file << "  }\n";
    file << "\n";
    file << "  function emitScroll() {\n";
    file << "    scrollRaf = 0;\n";
    file << "    if (!scrollForwarding) return;\n";
    file << "    postToTrustedTop({\n";
    file << "      type: \"INLINE_EDIT_SCROLL\",\n";
    file << "      scrollX: window.scrollX,\n";
    file << "      scrollY: window.scrollY,\n";
    file << "    });\n";
    file << "  }\n";
    file << "\n";
    file << "  window.addEventListener(\n";
    file << "    \"scroll\",\n";
    file << "    function () {\n";
    file << "      if (!scrollForwarding || scrollRaf) return;\n";
    file << "      scrollRaf = requestAnimationFrame(emitScroll);\n";
    file << "    },\n";
    file << "    { passive: true, capture: true },\n";
    file << "  );\n";
    file << "\n";
    file << "  async function handleCaptureRequest(event) {\n";
    file << "    const requestId = event.data.requestId;\n";
    file << "    const scrollX = window.scrollX;\n";
    file << "    const scrollY = window.scrollY;\n";
    file << "    const width = window.innerWidth;\n";
    file << "    const height = window.innerHeight;\n";
    file << "\n";
    file << "    function postResult(dataUrl) {\n";
    file << "      postToTrustedTop({\n";
    file << "        type: \"INLINE_EDIT_SCREENSHOT_RESULT\",\n";
    file << "        requestId,\n";
    file << "        dataUrl,\n";
    file << "        scrollX,\n";
    file << "        scrollY,\n";
    file << "      });\n";
    file << "    }\n";
    file << "\n";
    file << "    try {\n";
    file << "      // Wait for any pending web fonts to resolve so both inline metrics and\n";
    file << "      // the @font-face inlining below see the same loaded faces.\n";
    file << "      if (document.fonts && document.fonts.ready) {\n";
    file << "        try {\n";
    file << "          await document.fonts.ready;\n";
    file << "        } catch (_error) {}\n";
    file << "      }\n";
    file << "\n";
    file << "      const clone = document.documentElement.cloneNode(true);\n";
    file << "      inlineAll(document.documentElement, clone);\n";
    file << "\n";
    file << "      const removedNodes = clone.querySelectorAll(\"script,link[rel=\\\"stylesheet\\\"],style\");\n";
    file << "      for (let index = 0; index < removedNodes.length; index += 1) {\n";
    file << "        removedNodes[index].remove();\n";
    file << "      }\n";
    file << "\n";
    file << "      stripExternal(clone);\n";
    file << "\n";
    file << "      // Re-embed web fonts as data-URI @font-face rules so the SVG rasterizer\n";
    file << "      // can resolve them — external font URLs aren't fetched during\n";
    file << "      // foreignObject rendering, which would otherwise force a fallback face\n";
    file << "      // and change text metrics.\n";
    file << "      const inlinedFontCss = await buildInlinedFontCss();\n";
    file << "      if (inlinedFontCss) {\n";
    file << "        const styleEl = document.createElement(\"style\");\n";
    file << "        styleEl.textContent = inlinedFontCss;\n";
    file << "        const head = clone.querySelector(\"head\");\n";
    file << "        if (head) head.appendChild(styleEl);\n";
    file << "        else clone.insertBefore(styleEl, clone.firstChild);\n";
    file << "      }\n";
    file << "\n";
    file << "      const html = new XMLSerializer().serializeToString(clone);\n";
    file << "      const svg =\n";
    file << "        `<svg xmlns=\\\"http://www.w3.org/2000/svg\\\" width=\\\"${width}\\\" height=\\\"${height}\\\">` +\n";
    file << "        '<foreignObject width=\\\"100%\\\" height=\\\"100%\\\">' +\n";
    file << "        `<div xmlns=\\\"http://www.w3.org/1999/xhtml\\\" style=\\\"width:${width}px;height:${height}px;overflow:hidden\\\">` +\n";
    file << "        `<div style=\\\"position:relative;left:-${scrollX}px;top:-${scrollY}px\\\">` +\n";
    file << "        html +\n";
    file << "        \"</div></div></foreignObject></svg>\";\n";
    file << "      const svgUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;\n";
    file << "      const image = new Image();\n";
    file << "      image.onload = function () {\n";
    file << "        const canvas = document.createElement(\"canvas\");\n";
    file << "        canvas.width = width;\n";
    file << "        canvas.height = height;\n";
    file << "        canvas.getContext(\"2d\").drawImage(image, 0, 0);\n";
    file << "        postResult(canvas.toDataURL(\"image/png\"));\n";
    file << "      };\n";
    file << "      image.onerror = function () {\n";
    file << "        postResult(null);\n";
    file << "      };\n";
    file << "      image.src = svgUrl;\n";
    file << "    } catch (_error) {\n";
    file << "      postResult(null);\n";
    file << "    }\n";
    file << "  }\n";
    file << "\n";
    file << "  window.addEventListener(\"message\", function (event) {\n";
    file << "    if (!event.data) return;\n";
    file << "    // Only accept messages from the direct parent frame. Blocks sibling /\n";
    file << "    // unrelated-window postMessage senders that could otherwise reach us.\n";
    file << "    if (event.source !== window.parent) return;\n";
    file << "\n";
    file << "    const trustedParentOrigin = getTrustedParentOrigin(event);\n";
    file << "    if (!trustedParentOrigin) return;\n";
    file << "    trustedTopOrigin = trustedParentOrigin;\n";
    file << "\n";
    file << "    if (event.data.type === \"INLINE_EDIT_SCROLL_START\") {\n";
    file << "      scrollForwarding = true;\n";
    file << "      emitScroll();\n";
    file << "      return;\n";
    file << "    }\n";
    file << "\n";
    file << "    if (event.data.type === \"INLINE_EDIT_SCROLL_STOP\") {\n";
    file << "      scrollForwarding = false;\n";
    file << "      if (scrollRaf) cancelAnimationFrame(scrollRaf);\n";
    file << "      scrollRaf = 0;\n";
    file << "      return;\n";
    file << "    }\n";
    file << "\n";
    file << "    if (event.data.type !== \"INLINE_EDIT_CAPTURE_REQUEST\") return;\n";
    file << "\n";
    file << "    handleCaptureRequest(event);\n";
    file << "  });\n";
    file << "})();\n";
    file << "\n";
    file << "\n";
    file << "</script></body>\n";
    file << "</html>\n";

    file.close();
}

int main(int argc, char* argv[]) {
    if (argc != 2) {
        std::cerr << "Usage: " << argv[0] << " <output_filename>" << std::endl;
        return 1;
    }
    
    writeHtmlDocument(argv[1]);
    return 0;
}
