"""Install a prepared artifact set and derive the site's checksums from its bytes."""
import argparse, hashlib, json, shutil, zipfile
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument("--from-dir",type=Path,required=True);a=p.parse_args()
site=Path(__file__).resolve().parents[1]
version=json.loads((site.parent/"plugin-source/browser-extension/manifest.json").read_text(encoding="utf8"))["version"]
names=[f"tiktok-live-companion-{kind}-{version}{suffix}.zip" for kind,suffix in [("extension",""),("plugin",""),("service",""),("android","-source"),("ios","-source")]]
apk_name=f"tiktok-live-companion-android-{version}.apk"
if (a.from_dir/apk_name).is_file():names.append(apk_name)
for name in names:
 src=a.from_dir/name
 with zipfile.ZipFile(src) as z:
  if z.testzip():raise RuntimeError("Corrupt ZIP: "+name)
  if "extension" in name and json.loads(z.read("manifest.json"))["version"]!=version:raise RuntimeError("Manifest version mismatch")
for name in names:shutil.copy2(a.from_dir/name,site/"public/downloads"/name)
hashes="".join(hashlib.sha256((site/"public/downloads"/name).read_bytes()).hexdigest()+"  "+name+"\n" for name in names)
(site/"public/downloads"/f"tiktok-live-companion-{version}-SHA256.txt").write_text(hashes,encoding="utf8")
(site/"src/download-checksums.ts").write_text("// Generated by site/scripts/sync-downloads.py; do not edit by hand.\nexport const downloadChecksums = "+json.dumps(hashes)+";\n",encoding="utf8")
print(hashes)
