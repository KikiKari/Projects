def write_to_file(content, filename):
    """Write content to specified file"""
    try:
        with open(filename, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Successfully wrote HTML content to {filename}")
    except IOError as e:
        print(f"Error writing to file {filename}: {e}")
        raise

