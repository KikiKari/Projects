/** Install a prepared artifact set and derive the site's checksums from its bytes. */
import fs from 'fs';
import path from 'path';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';
import yargs from 'yargs';
import { hideBin } from 'yargs/helpers';
import AdmZip from 'adm-zip';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const argv = yargs(hideBin(process.argv))
  .option('fromDir', {
    type: 'string',
    demandOption: true,
    describe: 'Source directory'
  })
  .argv;

const site = path.resolve(__dirname, '../..');
const manifestPath = path.join(site, '../plugin-source/browser-extension/manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const version = manifest.version;

const kinds = [
  ['extension', ''],
  ['plugin', ''],
  ['service', ''],
  ['android', '-source'],
  ['ios', '-source']
];

let names = kinds.map(([kind, suffix]) => 
  `tiktok-live-companion-${kind}-${version}${suffix}.zip`
);

const apkName = `tiktok-live-companion-android-${version}.apk`;
const apkPath = path.join(argv.fromDir, apkName);
if (fs.existsSync(apkPath)) {
  names.push(apkName);
}

// Validate ZIP files
for (const name of names) {
  const src = path.join(argv.fromDir, name);
  const zip = new AdmZip(src);
  
  // Test ZIP integrity
  try {
    zip.testArchive();
  } catch (error) {
    throw new Error(`Corrupt ZIP: ${name}`);
  }
  
  // Check manifest version for extension files
  if (name.includes('extension')) {
    const manifestEntry = zip.getEntry('manifest.json');
    if (manifestEntry) {
      const zipManifest = JSON.parse(zip.readAsText(manifestEntry));
      if (zipManifest.version !== version) {
        throw new Error('Manifest version mismatch');
      }
    }
  }
}

// Copy files
const destDir = path.join(site, 'public/downloads');
if (!fs.existsSync(destDir)) {
  fs.mkdirSync(destDir, { recursive: true });
}

for (const name of names) {
  const src = path.join(argv.fromDir, name);
  const dest = path.join(destDir, name);
  fs.copyFileSync(src, dest);
}

// Generate hashes
let hashes = '';
for (const name of names) {
  const filePath = path.join(destDir, name);
  const fileBuffer = fs.readFileSync(filePath);
  const hash = createHash('sha256').update(fileBuffer).digest('hex');
  hashes += `${hash}  ${name}\n`;
}

// Write checksum file
const checksumFileName = `tiktok-live-companion-${version}-SHA256.txt`;
const checksumFilePath = path.join(destDir, checksumFileName);
fs.writeFileSync(checksumFilePath, hashes, 'utf8');

// Write TypeScript file
const tsContent = `// Generated by site/scripts/sync-downloads.py; do not edit by hand.\nexport const downloadChecksums = ${JSON.stringify(hashes)};\n`;
const tsPath = path.join(site, 'src/download-checksums.ts');
fs.writeFileSync(tsPath, tsContent, 'utf8');

console.log(hashes);
