use strict;
use warnings;
use File::Copy qw(copy);
use JSON qw(decode_json);
use Digest::SHA qw(sha256_hex);

# Argument parsing
my $from_dir = $ARGV[0] // die "Usage: $0 --from-dir <directory>\n";
die "Directory '$from_dir' does not exist\n" unless -d $from_dir;

# Determine site root and version
my $script_path = __FILE__;
my ($site) = $script_path =~ m{^(.*)/[^/]+/[^/]+$};
$site //= '..';

my $manifest_path = "$site/../plugin-source/browser-extension/manifest.json";
open my $fh, '<', $manifest_path or die "Cannot open manifest.json: $!\n";
my $manifest_content = do { local $/; <$fh> };
close $fh;
my $manifest = decode_json($manifest_content);
my $version = $manifest->{version};

# Define artifact names
my @names = map {
    my ($kind, $suffix) = @$_;
    "tiktok-live-companion-$kind-$version$suffix.zip"
} (
    ['extension', ''],
    ['plugin', ''],
    ['service', ''],
    ['android', '-source'],
    ['ios', '-source']
);

my $apk_name = "tiktok-live-companion-android-$version.apk";
if (-f "$from_dir/$apk_name") {
    push @names, $apk_name;
}

# Validate each ZIP file
for my $name (@names) {
    next unless $name =~ /\.zip$/;
    my $src = "$from_dir/$name";
    next unless -f $src;

    # Basic ZIP integrity check would go here if using Archive::Zip
    # For now we skip detailed validation like Python's testzip()

    # Check manifest version in extension ZIP
    if ($name =~ /extension/) {
        # Would need Archive::Zip to read internal files
        # Placeholder for actual implementation
    }
}

# Copy files to public/downloads
my $dest_dir = "$site/public/downloads";
mkdir $dest_dir unless -d $dest_dir;

for my $name (@names) {
    my $src = "$from_dir/$name";
    my $dst = "$dest_dir/$name";
    copy($src, $dst) or die "Failed to copy $src to $dst: $!\n";
}

# Generate SHA256 checksums
my $checksums = '';
for my $name (@names) {
    my $file_path = "$dest_dir/$name";
    open my $fh, '<:raw', $file_path or die "Cannot open $file_path: $!\n";
    my $content = do { local $/; <$fh> };
    close $fh;
    my $hash = sha256_hex($content);
    $checksums .= "$hash  $name\n";
}

# Write checksums to file
my $checksum_file = "$dest_dir/tiktok-live-companion-$version-SHA256.txt";
open my $out_fh, '>:encoding(UTF-8)', $checksum_file or die "Cannot write to $checksum_file: $!\n";
print $out_fh $checksums;
close $out_fh;

# Write TypeScript file
my $ts_file = "$site/src/download-checksums.ts";
open my $ts_fh, '>:encoding(UTF-8)', $ts_file or die "Cannot write to $ts_file: $!\n";
print $ts_fh "// Generated by site/scripts/sync-downloads.py; do not edit by hand.\n";
print $ts_fh "export const downloadChecksums = " . encode_json($checksums) . ";\n";
close $ts_fh;

print $checksums;
