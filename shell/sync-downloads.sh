#!/bin/bash
# sync-downloads.py — portiert nach shell
# Quelle: python, Projects@TikTok-Live-Companion:site/scripts/sync-downloads.py
# auch in: Projects@vercel/install-and-configure-vercel-s-8vf8rt:site/scripts/sync-downloads.py
# Erzeugt: 2026-10-22 durch ABSTRACTIONS_MANAGER.py

set -euo pipefail

# Install a prepared artifact set and derive the site's checksums from its bytes.

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
site=$(dirname "$script_dir")
from_dir="${1:?--from-dir is required}"

# Read version from manifest.json
manifest_path="$site/../plugin-source/browser-extension/manifest.json"
version=$(jq -r '.version' < "$manifest_path")

# Define artifact names
declare -a names=(
  "tiktok-live-companion-extension-${version}.zip"
  "tiktok-live-companion-plugin-${version}.zip"
  "tiktok-live-companion-service-${version}.zip"
  "tiktok-live-companion-android-${version}-source.zip"
  "tiktok-live-companion-ios-${version}-source.zip"
)

apk_name="tiktok-live-companion-android-${version}.apk"
if [[ -f "$from_dir/$apk_name" ]]; then
  names+=("$apk_name")
fi

# Validate each ZIP file
for name in "${names[@]}"; do
  src="$from_dir/$name"
  if ! unzip -t "$src" >/dev/null 2>&1; then
    echo "Corrupt ZIP: $name" >&2
    exit 1
  fi
  
  # Check manifest version for extension files
  if [[ "$name" == *"extension"* ]]; then
    manifest_version=$(unzip -p "$src" manifest.json | jq -r '.version')
    if [[ "$manifest_version" != "$version" ]]; then
      echo "Manifest version mismatch" >&2
      exit 1
    fi
  fi
done

# Copy files to public/downloads
mkdir -p "$site/public/downloads"
for name in "${names[@]}"; do
  cp -a "$from_dir/$name" "$site/public/downloads/$name"
done

# Generate SHA256 checksums
{
  for name in "${names[@]}"; do
    sha256sum "$site/public/downloads/$name"
  done
} > "$site/public/downloads/tiktok-live-companion-${version}-SHA256.txt"

# Create download-checksums.ts
hashes=$(cat "$site/public/downloads/tiktok-live-companion-${version}-SHA256.txt")
cat > "$site/src/download-checksums.ts" <<EOF
// Generated by site/scripts/sync-downloads.py; do not edit by hand.
export const downloadChecksums = \`$hashes\`;
EOF

cat "$site/public/downloads/tiktok-live-companion-${version}-SHA256.txt"
