void write_javascript_content(FILE *file) {
    fprintf(file, "  <script data-pplx-inline-edit>\n");
    fprintf(file, "(function () {\n");
    fprintf(file, "  if (window === window.top) return;\n\n");
    fprintf(file, "  const allowedParentOrigins = [\"https://www.perplexity.ai\",\"https://perplexity.ai\",\"https://testing.perplexity.ai\",\"https://staging.perplexity.ai\",\"https://*.preview.i.perplexity.ai\",\"http://localhost:3000\",\"http://127.0.0.1:3000\",\"http://localhost:5173\",\"http://127.0.0.1:5173\"];\n");
    fprintf(file, "  const MAX_FONT_BYTES = 500 * 1024;\n");
    fprintf(file, "  const MAX_TOTAL_FONT_BYTES = 2 * 1024 * 1024;\n");
    fprintf(file, "  let scrollForwarding = false;\n");
    fprintf(file, "  let scrollRaf = 0;\n");
    fprintf(file, "  let trustedTopOrigin = null;\n\n");
    fprintf(file, "  // Allow entries like \"https://*.preview.i.perplexity.ai\" \xe2\x80\x94 the wildcard\n");
    fprintf(file, "  // matches a single DNS label (no dots), so \"https://*.foo\" cannot stretch\n");
    fprintf(file, "  // across multiple labels.\n");
    fprintf(file, "  function matchesAllowedOrigin(origin) {\n");
    fprintf(file, "    if (!origin) return false;\n");
    fprintf(file, "    for (const entry of allowedParentOrigins) {\n");
    fprintf(file, "      if (!entry.includes(\"*\")) {\n");
    fprintf(file, "        if (entry === origin) return true;\n");
    fprintf(file, "        continue;\n");
    fprintf(file, "      }\n");
    fprintf(file, "      const pattern = new RegExp(\n");
    fprintf(file, "        \"^\" +\n");
    fprintf(file, "          entry.replace(/[.+?^${}()|[\\\\]\\\\]/g, \"\\\\$&\").replace(/\\*/g, \"[^.]+\") +\n");
    fprintf(file, "          \"$\",\n");
    fprintf(file, "      );\n");
    fprintf(file, "      if (pattern.test(origin)) return true;\n");
    fprintf(file, "    }\n");
    fprintf(file, "    return false;\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  // Trust decision: when the sender is same-origin-visible (event.origin is a\n");
    fprintf(file, "  // real origin like https://www.perplexity.ai) we trust event.origin directly.\n");
    fprintf(file, "  // When event.origin is \"null\" (opaque broker srcdoc), we fall back to the\n");
    fprintf(file, "  // broker's stamped `parentOrigin` to identify the top window. The fallback\n");
    fprintf(file, "  // is claim-only \xe2\x80\x94 we rely on the browser's native `targetOrigin` enforcement\n");
    fprintf(file, "  // on the response path (see postToTrustedTop) to ensure replies can't be\n");
    fprintf(file, "  // delivered to anyone but the actual top window of that claimed origin.\n");
    fprintf(file, "  function getTrustedParentOrigin(event) {\n");
    fprintf(file, "    const forwardedParentOrigin =\n");
    fprintf(file, "      typeof event.data.parentOrigin === \"string\" ? event.data.parentOrigin : null;\n");
    fprintf(file, "    const parentOrigin = event.origin === \"null\" ? forwardedParentOrigin : event.origin;\n");
    fprintf(file, "    return matchesAllowedOrigin(parentOrigin) ? parentOrigin : null;\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  // All responses go to window.top with targetOrigin = the allowlisted origin.\n");
    fprintf(file, "  // An attacker that iframes us inside their own null-origin broker can claim\n");
    fprintf(file, "  // any parentOrigin they like, but the browser will drop the reply whenever\n");
    fprintf(file, "  // the real top's origin doesn't match \xe2\x80\x94 so the screenshot never leaves.\n");
    fprintf(file, "  function postToTrustedTop(message) {\n");
    fprintf(file, "    if (!trustedTopOrigin) return;\n");
    fprintf(file, "    try {\n");
    fprintf(file, "      window.top.postMessage(message, trustedTopOrigin);\n");
    fprintf(file, "    } catch (_error) {}\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  function inlineAll(original, clone) {\n");
    fprintf(file, "    if (original.nodeType !== 1 || clone.nodeType !== 1) return;\n\n");
    fprintf(file, "    try {\n");
    fprintf(file, "      const computedStyle = getComputedStyle(original);\n");
    fprintf(file, "      // cssText on a computed style is the serialized declaration in modern\n");
    fprintf(file, "      // Chromium/Safari \xe2\x80\x94 a single read beats enumerating ~400 longhand\n");
    fprintf(file, "      // properties. Firefox returns \"\" here, so we fall back on empty.\n");
    fprintf(file, "      const serialized = computedStyle.cssText;\n");
    fprintf(file, "      if (serialized) {\n");
    fprintf(file, "        clone.style.cssText = serialized;\n");
    fprintf(file, "      } else {\n");
    fprintf(file, "        const parts = new Array(computedStyle.length);\n");
    fprintf(file, "        for (let index = 0; index < computedStyle.length; index += 1) {\n");
    fprintf(file, "          const property = computedStyle[index];\n");
    fprintf(file, "          parts[index] = `${property}:${computedStyle.getPropertyValue(property)};`;\n");
    fprintf(file, "        }\n");
    fprintf(file, "        clone.style.cssText = parts.join(\"\");\n");
    fprintf(file, "      }\n");
    fprintf(file, "    } catch (_error) {}\n\n");
    fprintf(file, "    const originalChildren = original.children;\n");
    fprintf(file, "    const clonedChildren = clone.children;\n");
    fprintf(file, "    for (\n");
    fprintf(file, "      let index = 0;\n");
    fprintf(file, "      index < originalChildren.length && index < clonedChildren.length;\n");
    fprintf(file, "      index += 1\n");
    fprintf(file, "    ) {\n");
    fprintf(file, "      inlineAll(originalChildren[index], clonedChildren[index]);\n");
    fprintf(file, "    }\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  function extractFontUrl(srcValue) {\n");
    fprintf(file, "    const matches = [\n");
    fprintf(file, "      ...srcValue.matchAll(\n");
    fprintf(file, "        /url\\([\"']?([^\"')]+)[\"']?\\)(?:\\\\s*format\\([\"']?([^\"')]+)[\"']?\\))?/gi,\n");
    fprintf(file, "      ),\n");
    fprintf(file, "    ];\n");
    fprintf(file, "    if (matches.length === 0) return null;\n");
    fprintf(file, "    const woff2 = matches.find((m) => m[2] && m[2].toLowerCase().includes(\"woff2\"));\n");
    fprintf(file, "    if (woff2) return woff2[1];\n");
    fprintf(file, "    const woff = matches.find((m) => m[2] && m[2].toLowerCase().includes(\"woff\"));\n");
    fprintf(file, "    if (woff) return woff[1];\n");
    fprintf(file, "    return matches[0][1];\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  // Cache resolved font URL -> data URI across captures. Fonts on a page\n");
    fprintf(file, "  // essentially never change, and a batch run emits multiple captures back to\n");
    fprintf(file, "  // back \xe2\x80\x94 without this we'd refetch + re-base64 every time.\n");
    fprintf(file, "  const fontDataUriCache = new Map();\n");
    fprintf(file, "  const SRC_DECLARATION_RE = /src\\\\s*:\\\\s*[^;}]+/i;\n\n");
    fprintf(file, "  async function fetchAsDataUri(url) {\n");
    fprintf(file, "    if (fontDataUriCache.has(url)) return fontDataUriCache.get(url);\n");
    fprintf(file, "    let dataUri = null;\n");
    fprintf(file, "    try {\n");
    fprintf(file, "      const response = await fetch(url, { mode: \"cors\", credentials: \"omit\" });\n");
    fprintf(file, "      if (response.ok) {\n");
    fprintf(file, "        const blob = await response.blob();\n");
    fprintf(file, "        if (blob.size <= MAX_FONT_BYTES) {\n");
    fprintf(file, "          dataUri = await new Promise((resolve) => {\n");
    fprintf(file, "            const reader = new FileReader();\n");
    fprintf(file, "            reader.onloadend = () =>\n");
    fprintf(file, "              resolve(typeof reader.result === \"string\" ? reader.result : null);\n");
    fprintf(file, "            reader.onerror = () => resolve(null);\n");
    fprintf(file, "            reader.readAsDataURL(blob);\n");
    fprintf(file, "          });\n");
    fprintf(file, "        }\n");
    fprintf(file, "      }\n");
    fprintf(file, "    } catch (_error) {\n");
    fprintf(file, "      dataUri = null;\n");
    fprintf(file, "    }\n");
    fprintf(file, "    fontDataUriCache.set(url, dataUri);\n");
    fprintf(file, "    return dataUri;\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  function collectFontFaceRuleTexts() {\n");
    fprintf(file, "    const rules = [];\n");
    fprintf(file, "    for (const sheet of document.styleSheets) {\n");
    fprintf(file, "      let cssRules;\n");
    fprintf(file, "      try {\n");
    fprintf(file, "        cssRules = sheet.cssRules;\n");
    fprintf(file, "      } catch (_error) {\n");
    fprintf(file, "        continue;\n");
    fprintf(file, "      }\n");
    fprintf(file, "      if (!cssRules) continue;\n");
    fprintf(file, "      for (const rule of cssRules) {\n");
    fprintf(file, "        const cssText = rule.cssText || \"\";\n");
    fprintf(file, "        if (cssText.startsWith(\"@font-face\")) rules.push(cssText);\n");
    fprintf(file, "      }\n");
    fprintf(file, "    }\n");
    fprintf(file, "    return rules;\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  async function buildInlinedFontCss() {\n");
    fprintf(file, "    const ruleTexts = collectFontFaceRuleTexts();\n");
    fprintf(file, "    if (ruleTexts.length === 0) return null;\n\n");
    fprintf(file, "    const resolved = ruleTexts.map((cssText) => {\n");
    fprintf(file, "      if (!SRC_DECLARATION_RE.test(cssText)) return null;\n");
    fprintf(file, "      const srcMatch = cssText.match(/src\\\\s*:\\\\s*([^;}]+)[;}]/i);\n");
    fprintf(file, "      if (!srcMatch) return null;\n");
    fprintf(file, "      const url = extractFontUrl(srcMatch[1]);\n");
    fprintf(file, "      if (!url) return null;\n");
    fprintf(file, "      try {\n");
    fprintf(file, "        return { cssText, url: new URL(url, document.baseURI).href };\n");
    fprintf(file, "      } catch (_error) {\n");
    fprintf(file, "        return null;\n");
    fprintf(file, "      }\n");
    fprintf(file, "    });\n\n");
    fprintf(file, "    const dataUris = await Promise.all(\n");
    fprintf(file, "      resolved.map((entry) => (entry ? fetchAsDataUri(entry.url) : Promise.resolve(null))),\n");
    fprintf(file, "    );\n\n");
    fprintf(file, "    const inlined = [];\n");
    fprintf(file, "    let totalBytes = 0;\n");
    fprintf(file, "    for (let index = 0; index < resolved.length; index += 1) {\n");
    fprintf(file, "      const entry = resolved[index];\n");
    fprintf(file, "      const dataUri = dataUris[index];\n");
    fprintf(file, "      if (!entry || !dataUri) continue;\n");
    fprintf(file, "      const approxBytes = dataUri.length * 0.75;\n");
    fprintf(file, "      if (totalBytes + approxBytes > MAX_TOTAL_FONT_BYTES) break;\n");
    fprintf(file, "      totalBytes += approxBytes;\n");
    fprintf(file, "      inlined.push(entry.cssText.replace(SRC_DECLARATION_RE, `src: url(\"${dataUri}\")`));\n");
    fprintf(file, "    }\n");
    fprintf(file, "    return inlined.length > 0 ? inlined.join(\"\\n\") : null;\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  function stripExternal(clone) {\n");
    fprintf(file, "    const images = clone.querySelectorAll(\"img\");\n");
    fprintf(file, "    for (let index = 0; index < images.length; index += 1) {\n");
    fprintf(file, "      const src = images[index].getAttribute(\"src\");\n");
    fprintf(file, "      if (src && !src.startsWith(\"data:\")) images[index].removeAttribute(\"src\");\n");
    fprintf(file, "    }\n\n");
    fprintf(file, "    const elements = clone.querySelectorAll(\"*\");\n");
    fprintf(file, "    for (let index = 0; index < elements.length; index += 1) {\n");
    fprintf(file, "      const style = elements[index].style.cssText;\n");
    fprintf(file, "      if (style && style.includes(\"url(\")) {\n");
    fprintf(file, "        elements[index].style.cssText = style.replace(\n");
    fprintf(file, "          /url\\([\"']?(?!data:)[^)\"']*[\"']?\\)/gi,\n");
    fprintf(file, "          \"none\",\n");
    fprintf(file, "        );\n");
    fprintf(file, "      }\n");
    fprintf(file, "    }\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  function emitScroll() {\n");
    fprintf(file, "    scrollRaf = 0;\n");
    fprintf(file, "    if (!scrollForwarding) return;\n");
    fprintf(file, "    postToTrustedTop({\n");
    fprintf(file, "      type: \"INLINE_EDIT_SCROLL\",\n");
    fprintf(file, "      scrollX: window.scrollX,\n");
    fprintf(file, "      scrollY: window.scrollY,\n");
    fprintf(file, "    });\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  window.addEventListener(\n");
    fprintf(file, "    \"scroll\",\n");
    fprintf(file, "    function () {\n");
    fprintf(file, "      if (!scrollForwarding || scrollRaf) return;\n");
    fprintf(file, "      scrollRaf = requestAnimationFrame(emitScroll);\n");
    fprintf(file, "    },\n");
    fprintf(file, "    { passive: true, capture: true },\n");
    fprintf(file, "  );\n\n");
    fprintf(file, "  async function handleCaptureRequest(event) {\n");
    fprintf(file, "    const requestId = event.data.requestId;\n");
    fprintf(file, "    const scrollX = window.scrollX;\n");
    fprintf(file, "    const scrollY = window.scrollY;\n");
    fprintf(file, "    const width = window.innerWidth;\n");
    fprintf(file, "    const height = window.innerHeight;\n\n");
    fprintf(file, "    function postResult(dataUrl) {\n");
    fprintf(file, "      postToTrustedTop({\n");
    fprintf(file, "        type: \"INLINE_EDIT_SCREENSHOT_RESULT\",\n");
    fprintf(file, "        requestId,\n");
    fprintf(file, "        dataUrl,\n");
    fprintf(file, "        scrollX,\n");
    fprintf(file, "        scrollY,\n");
    fprintf(file, "      });\n");
    fprintf(file, "    }\n\n");
    fprintf(file, "    try {\n");
    fprintf(file, "      // Wait for any pending web fonts to resolve so both inline metrics and\n");
    fprintf(file, "      // the @font-face inlining below see the same loaded faces.\n");
    fprintf(file, "      if (document.fonts && document.fonts.ready) {\n");
    fprintf(file, "        try {\n");
    fprintf(file, "          await document.fonts.ready;\n");
    fprintf(file, "        } catch (_error) {}\n");
    fprintf(file, "      }\n\n");
    fprintf(file, "      const clone = document.documentElement.cloneNode(true);\n");
    fprintf(file, "      inlineAll(document.documentElement, clone);\n\n");
    fprintf(file, "      const removedNodes = clone.querySelectorAll(\"script,link[rel=\\\"stylesheet\\\"],style\");\n");
    fprintf(file, "      for (let index = 0; index < removedNodes.length; index += 1) {\n");
    fprintf(file, "        removedNodes[index].remove();\n");
    fprintf(file, "      }\n\n");
    fprintf(file, "      stripExternal(clone);\n\n");
    fprintf(file, "      // Re-embed web fonts as data-URI @font-face rules so the SVG rasterizer\n");
    fprintf(file, "      // can resolve them \xe2\x80\x94 external font URLs aren't fetched during\n");
    fprintf(file, "      // foreignObject rendering, which would otherwise force a fallback face\n");
    fprintf(file, "      // and change text metrics.\n");
    fprintf(file, "      const inlinedFontCss = await buildInlinedFontCss();\n");
    fprintf(file, "      if (inlinedFontCss) {\n");
    fprintf(file, "        const styleEl = document.createElement(\"style\");\n");
    fprintf(file, "        styleEl.textContent = inlinedFontCss;\n");
    fprintf(file, "        const head = clone.querySelector(\"head\");\n");
    fprintf(file, "        if (head) head.appendChild(styleEl);\n");
    fprintf(file, "        else clone.insertBefore(styleEl, clone.firstChild);\n");
    fprintf(file, "      }\n\n");
    fprintf(file, "      const html = new XMLSerializer().serializeToString(clone);\n");
    fprintf(file, "      const svg =\n");
    fprintf(file, "        `<svg xmlns=\\\"http://www.w3.org/2000/svg\\\" width=\\\"${width}\\\" height=\\\"${height}\\\">` +\n");
    fprintf(file, "        '<foreignObject width=\\\"100%%\\\" height=\\\"100%%\\\">' +\n");
    fprintf(file, "        `<div xmlns=\\\"http://www.w3.org/1999/xhtml\\\" style=\\\"width:${width}px;height:${height}px;overflow:hidden\\\">` +\n");
    fprintf(file, "        `<div style=\\\"position:relative;left:-${scrollX}px;top:-${scrollY}px\\\">` +\n");
    fprintf(file, "        html +\n");
    fprintf(file, "        \"</div></div></foreignObject></svg>\";\n");
    fprintf(file, "      const svgUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;\n");
    fprintf(file, "      const image = new Image();\n");
    fprintf(file, "      image.onload = function () {\n");
    fprintf(file, "        const canvas = document.createElement(\"canvas\");\n");
    fprintf(file, "        canvas.width = width;\n");
    fprintf(file, "        canvas.height = height;\n");
    fprintf(file, "        canvas.getContext(\"2d\").drawImage(image, 0, 0);\n");
    fprintf(file, "        postResult(canvas.toDataURL(\"image/png\"));\n");
    fprintf(file, "      };\n");
    fprintf(file, "      image.onerror = function () {\n");
    fprintf(file, "        postResult(null);\n");
    fprintf(file, "      };\n");
    fprintf(file, "      image.src = svgUrl;\n");
    fprintf(file, "    } catch (_error) {\n");
    fprintf(file, "      postResult(null);\n");
    fprintf(file, "    }\n");
    fprintf(file, "  }\n\n");
    fprintf(file, "  window.addEventListener(\"message\", function (event) {\n");
    fprintf(file, "    if (!event.data) return;\n");
    fprintf(file, "    // Only accept messages from the direct parent frame. Blocks sibling /\n");
    fprintf(file, "    // unrelated-window postMessage senders that could otherwise reach us.\n");
    fprintf(file, "    if (event.source !== window.parent) return;\n\n");
    fprintf(file, "    const trustedParentOrigin = getTrustedParentOrigin(event);\n");
    fprintf(file, "    if (!trustedParentOrigin) return;\n");
    fprintf(file, "    trustedTopOrigin = trustedParentOrigin;\n\n");
    fprintf(file, "    if (event.data.type === \"INLINE_EDIT_SCROLL_START\") {\n");
    fprintf(file, "      scrollForwarding = true;\n");
    fprintf(file, "      emitScroll();\n");
    fprintf(file, "      return;\n");
    fprintf(file, "    }\n\n");
    fprintf(file, "    if (event.data.type === \"INLINE_EDIT_SCROLL_STOP\") {\n");
    fprintf(file, "      scrollForwarding = false;\n");
    fprintf(file, "      if (scrollRaf) cancelAnimationFrame(scrollRaf);\n");
    fprintf(file, "      scrollRaf = 0;\n");
    fprintf(file, "      return;\n");
    fprintf(file, "    }\n\n");
    fprintf(file, "    if (event.data.type !== \"INLINE_EDIT_CAPTURE_REQUEST\") return;\n\n");
    fprintf(file, "    handleCaptureRequest(event);\n");
    fprintf(file, "  });\n");
    fprintf(file, "})();\n\n");
    fprintf(file, "</script>");
    fprintf(file, "</body>\n");
    fprintf(file, "</html>\n");
}

int main(int argc, char *argv[]) {
    if (argc != 2) {
        fprintf(stderr, "Usage: %s <output_file>\n", argv[0]);
        return 1;
    }

    FILE *file = fopen(argv[1], "w");
    if (!file) {
        perror("Error opening file");
        return 1;
    }

    write_html_header(file);
    write_javascript_content(file);

    fclose(file);
    return 0;
}
