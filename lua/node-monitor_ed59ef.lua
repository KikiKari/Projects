local function escape_html(text)
  local replacements = {
    ["&"] = "&amp;",
    ["<"] = "&lt;",
    [">"] = "&gt;",
    ['"'] = "&quot;",
    ["'"] = "&#39;"
  }
  return text:gsub("[&<>\"']", replacements)
end

local function generate_html()
  local html = {}
  
  table.insert(html, '<!DOCTYPE html>')
  table.insert(html, '<html lang="en">')
  table.insert(html, '<head>')
  table.insert(html, '  <meta charset="UTF-8">')
  table.insert(html, '  <meta name="viewport" content="width=device-width, initial-scale=1.0">')
  table.insert(html, '  <title>OpenClaw — Live Node Monitor</title>')
  table.insert(html, '  <style>')
  table.insert(html, '    :root { --bg: #0d1117; --surface: #161b22; --border: #30363d;')
  table.insert(html, '            --text: #e6edf3; --green: #3fb950; --red: #f85149; --accent: #58a6ff; }')
  table.insert(html, '    * { box-sizing: border-box; margin: 0; padding: 0; }')
  table.insert(html, '    body { background: var(--bg); color: var(--text);')
  table.insert(html, '           font-family: -apple-system, sans-serif; padding: 1.5rem; }')
  table.insert(html, '    h1   { color: var(--accent); margin-bottom: 1rem; font-size: 1.2rem; }')
  table.insert(html, '    canvas { display: block; border: 1px solid var(--border);')
  table.insert(html, '             border-radius: 8px; background: var(--surface); }')
  table.insert(html, '    #log { margin-top: 1rem; height: 140px; overflow-y: auto;')
  table.insert(html, '           background: var(--surface); border: 1px solid var(--border);')
  table.insert(html, '           border-radius: 8px; padding: .75rem; font-size: .78rem;')
  table.insert(html, '           font-family: monospace; color: #8b949e; }')
  table.insert(html, '    #log .err { color: var(--red); }')
  table.insert(html, '    #log .ok  { color: var(--green); }')
  table.insert(html, '  </style>')
  table.insert(html, '</head>')
  table.insert(html, '<body>')
  table.insert(html, '  <h1>OpenClaw — Live Node Monitor</h1>')
  table.insert(html, '  <canvas id="canvas" width="640" height="220"></canvas>')
  table.insert(html, '  <div id="log"></div>')
  table.insert(html, '')
  table.insert(html, '  <script>')
  table.insert(html, '    /* HTML5 Canvas — animated node topology */')
  table.insert(html, '    const canvas = document.getElementById("canvas");')
  table.insert(html, '    const ctx    = canvas.getContext("2d");')
  table.insert(html, '    const log    = document.getElementById("log");')
  table.insert(html, '    const GATEWAY_URL = window.OPENCLAW_WS || "ws://localhost:8080/ws";')
  table.insert(html, '')
  table.insert(html, '    const nodes = [')
  table.insert(html, '      { id: "GW1", x: 160, y: 110, status: "unknown" },')
  table.insert(html, '      { id: "GW2", x: 480, y: 110, status: "unknown" },')
  table.insert(html, '      { id: "HUB", x: 320, y:  55, status: "ok"      },')
  table.insert(html, '    ];')
  table.insert(html, '    const edges = [[0,2],[1,2]];')
  table.insert(html, '')
  table.insert(html, '    let pulse = 0;')
  table.insert(html, '')
  table.insert(html, '    function drawNode(n) {')
  table.insert(html, '      const color = n.status === "ok" ? "#3fb950" : n.status === "error" ? "#f85149" : "#8b949e";')
  table.insert(html, '      ctx.beginPath();')
  table.insert(html, '      ctx.arc(n.x, n.y, 22 + (n.status === "ok" ? Math.sin(pulse) * 3 : 0), 0, Math.PI * 2);')
  table.insert(html, '      ctx.strokeStyle = color;')
  table.insert(html, '      ctx.lineWidth = 2;')
  table.insert(html, '      ctx.stroke();')
  table.insert(html, '      ctx.fillStyle = "#161b22";')
  table.insert(html, '      ctx.fill();')
  table.insert(html, '      ctx.fillStyle = color;')
  table.insert(html, '      ctx.font = "bold 11px monospace";')
  table.insert(html, '      ctx.textAlign = "center";')
  table.insert(html, '      ctx.textBaseline = "middle";')
  table.insert(html, '      ctx.fillText(n.id, n.x, n.y);')
  table.insert(html, '    }')
  table.insert(html, '')
  table.insert(html, '    function drawEdge(a, b, active) {')
  table.insert(html, '      ctx.beginPath();')
  table.insert(html, '      ctx.moveTo(nodes[a].x, nodes[a].y);')
  table.insert(html, '      ctx.lineTo(nodes[b].x, nodes[b].y);')
  table.insert(html, '      ctx.strokeStyle = active ? "#3fb95066" : "#30363d";')
  table.insert(html, '      ctx.lineWidth = active ? 2 : 1;')
  table.insert(html, '      ctx.setLineDash(active ? [] : [4, 4]);')
  table.insert(html, '      ctx.stroke();')
  table.insert(html, '      ctx.setLineDash([]);')
  table.insert(html, '    }')
  table.insert(html, '')
  table.insert(html, '    function render() {')
  table.insert(html, '      ctx.clearRect(0, 0, canvas.width, canvas.height);')
  table.insert(html, '      edges.forEach(([a, b]) => drawEdge(a, b, nodes[a].status === "ok" && nodes[b].status === "ok"));')
  table.insert(html, '      nodes.forEach(drawNode);')
  table.insert(html, '      pulse += 0.07;')
  table.insert(html, '      requestAnimationFrame(render);')
  table.insert(html, '    }')
  table.insert(html, '    render();')
  table.insert(html, '')
  table.insert(html, '    function addLog(msg, type = "") {')
  table.insert(html, '      const el = document.createElement("div");')
  table.insert(html, '      el.className = type;')
  table.insert(html, '      el.textContent = `[${new Date().toLocaleTimeString()}] ${msg}`;')
  table.insert(html, '      log.prepend(el);')
  table.insert(html, '      if (log.children.length > 60) log.lastChild.remove();')
  table.insert(html, '    }')
  table.insert(html, '')
  table.insert(html, '    /* HTML5 WebSocket — real-time gateway events */')
  table.insert(html, '    function connectWS() {')
  table.insert(html, '      const ws = new WebSocket(GATEWAY_URL);')
  table.insert(html, '      ws.onopen  = () => { addLog("WebSocket connected", "ok"); nodes[2].status = "ok"; };')
  table.insert(html, '      ws.onclose = () => { addLog("WebSocket closed — retrying in 3s", "err");')
  table.insert(html, '                           nodes.forEach(n => n.status = "error");')
  table.insert(html, '                           setTimeout(connectWS, 3000); };')
  table.insert(html, '      ws.onerror = () => addLog("WebSocket error", "err");')
  table.insert(html, '      ws.onmessage = ({ data }) => {')
  table.insert(html, '        try {')
  table.insert(html, '          const { node, status, latency } = JSON.parse(data);')
  table.insert(html, '          const n = nodes.find(n => n.id === node);')
  table.insert(html, '          if (n) n.status = status;')
  table.insert(html, '          addLog(`${node} — ${status} (${latency}ms)`, status === "ok" ? "ok" : "err");')
  table.insert(html, '        } catch { addLog(data); }')
  table.insert(html, '      };')
  table.insert(html, '    }')
  table.insert(html, '')
  table.insert(html, '    /* HTML5 Server-Sent Events — fallback */')
  table.insert(html, '    function connectSSE() {')
  table.insert(html, '      const es = new EventSource(GATEWAY_URL.replace("ws","http").replace("/ws","/events"));')
  table.insert(html, '      es.onmessage = ({ data }) => addLog(`SSE: ${data}`, "ok");')
  table.insert(html, '      es.onerror   = () => addLog("SSE stream error", "err");')
  table.insert(html, '    }')
  table.insert(html, '')
  table.insert(html, '    /* HTML5 localStorage — persist last known state */')
  table.insert(html, '    window.addEventListener("beforeunload", () =>')
  table.insert(html, '      localStorage.setItem("openclaw-nodes", JSON.stringify(nodes)));')
  table.insert(html, '    const saved = localStorage.getItem("openclaw-nodes");')
  table.insert(html, '    if (saved) JSON.parse(saved).forEach((s, i) => nodes[i].status = s.status);')
  table.insert(html, '')
  table.insert(html, '    "WebSocket" in window ? connectWS() : connectSSE();')
  table.insert(html, '  </script>')
  table.insert(html, '</body>')
  table.insert(html, '</html>')
  
  return table.concat(html, "\n")
end

